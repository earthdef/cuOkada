# render cutde's common.cu (MIT, T. Ben Thompson) and turn it into a templated host/device header
import re
import sys
import mako.lookup
import cutde

lookup = mako.lookup.TemplateLookup(directories=[cutde.__path__[0]])
wrapper = """<%namespace name="common" file="common.cu"/>
${common.defs("", "double")}
WITHIN_KERNEL Real3 disp_fs(Real3 obs, Real3 tri0, Real3 tri1, Real3 tri2, Real3 slip, Real nu) {
${common.disp_fs("tri")}
    return full_out;
}
WITHIN_KERNEL Real3 disp_hs(Real3 obs, Real3 tri0, Real3 tri1, Real3 tri2, Real3 slip, Real nu) {
${common.disp_hs("tri")}
    return full_out;
}
WITHIN_KERNEL Real6 strain_fs(Real3 obs, Real3 tri0, Real3 tri1, Real3 tri2, Real3 slip, Real nu) {
${common.strain_fs("tri")}
    return full_out;
}
WITHIN_KERNEL Real6 strain_hs(Real3 obs, Real3 tri0, Real3 tri1, Real3 tri2, Real3 slip, Real nu) {
${common.strain_hs("tri")}
    return full_out;
}
"""
src = mako.template.Template(wrapper, lookup=lookup).render(backend="cpp")

# drop the preamble: include guard, defines, structs and the print helpers
src = src[src.index("WITHIN_KERNEL Real2 add2"):]
src = src.replace("#endif\n", "", 1) if src.lstrip().startswith("#endif") else src
src = re.sub(r"WITHIN_KERNEL void print\d?\([^{]*\{[^}]*\}\n", "", src)
src = src.replace("#endif", "")
# the names of all functions, to call them with an explicit <Real>
names = re.findall(r"WITHIN_KERNEL\s+\w+\s+(\w+)\s*\(", src)
src = re.sub(r"\b(" + "|".join(names) + r")\s*\(", r"\1<Real>(", src)
src = re.sub(r"(WITHIN_KERNEL\s+\w+\s+\w+)<Real>\(", r"\1(", src)
src = src.replace("WITHIN_KERNEL", "template <typename Real>\nCUOKADA_HD inline")
src = re.sub(r"\bReal([236])\b", r"V\1<Real>", src)
src = re.sub(r"\bEPS\b", "eps<Real>()", src)
src = re.sub(r"\bNAN\b", "nan<Real>()", src)
# floating literals and pi in the precision of Real, so that floats don't promote to double
src = re.sub(r"(?<![\w.])(\d+\.\d*(?:[eE][-+]?\d+)?)f?(?![\w.])", r"Real(\1)", src)
src = re.sub(r"\bM_PI\b", "Real(M_PI)", src)
# tidy: collapse runs of blank lines and trailing spaces
src = re.sub(r"[ \t]+\n", "\n", src)
src = re.sub(r"\n{3,}", "\n\n", src)

header = """// -*- c++ -*-
//
// triangular dislocation elements in a full and a half space, after Nikkhoo and Walter (2015),
// ported from cutde (https://github.com/tbenthompson/cutde) common.cu, generated by tools/port_cutde.py; do not edit
//
// Copyright (c) 2021 T. Ben Thompson, MIT License; see LICENSE

#pragma once

#include "common.h"

namespace cuokada::tde {

"""
footer = "\n} // namespace cuokada::tde\n\n// end of file\n"
open(sys.argv[1], "w").write(header + src.strip() + "\n" + footer)
print(f"{len(names)} functions:", " ".join(names))
